void print_string_at_vgap(uint16_t x, uint16_t y, const char* str)
{
    while(*str != '\0')
    {
        print_char_at_vgap(x, y, *str);
        x += 8;

        str++;
    }
}

void print_string_vgap(const char* str)
{
    while(*str != '\0')
    { 
        print_char(*str);

        str++;
    }
}

void print_char_at_vgap(uint16_t x, uint16_t y, uint8_t ch)
{    
    uint16_t startx = x;
    uint16_t starty = y;

    for (uint8_t row = 0; row < 8; row++)
    {
        uint8_t line = font8[ch][row];
        uint8_t mask = 1;

        for (int8_t col = 0; col < 8; col++)
        {
            uint8_t bit = (line & mask) >> col;
            mask <<= 1;

            if(bit == 1)
            {
                drawPixel(x, y, fgColor);
            }
            else
            {
                drawPixel(x, y, bgColor);
            }

            x++;
        }

        x = startx;
        y++;        
    }      
}

void print_char(uint8_t ch)
{    
    if(vgay >= 200)
    {
        vgay = 0;
    }

    if(vgax > 320)
    {
        vgax = 0;
    }

    switch (ch)
    {
    case '\n':
        vgay += 8;
        vgax = 0;
        
        return;

    case '\t':
        vgax += 16;
        return;

    default:
        break;
    }
    
    uint16_t start_x = vgax;
    uint16_t start_y = vgay;

    for (uint8_t row = 0; row < 8; row++)
    {
        uint8_t line = font8[ch][row];
        uint8_t mask = 1;

        for (int8_t col = 0; col < 8; col++)
        {
            uint8_t bit = (line & mask) >> col;
            mask <<= 1;

            if(bit == 1)
            {
                drawPixel(start_x, start_y, fgColor);
            }
            else
            {
                drawPixel(start_x, start_y, bgColor);
            }

            start_x++;
        }
        
        start_x = vgax;        
        start_y++;
    }

    vgax += 8;    
        
    if(vgax >= WINDOW_WIDTH)
    {
        vgax = 0;
        vgay += 8;
    }
}

